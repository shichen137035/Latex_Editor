const { app, BrowserWindow } = require("electron");
const { mkdtempSync, mkdirSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { resolve } = require("node:path");
const assert = require("node:assert/strict");
const root = mkdtempSync(resolve(tmpdir(), "texweave-table-editor-"));
const projects = resolve(root, "projects"); mkdirSync(projects);
app.setPath("userData", resolve(root, "profile"));
const delay = ms => new Promise(done => setTimeout(done, ms));
let page;
const errors = [];
const evaluate = script => page.webContents.executeJavaScript(script, true).catch(error => { console.error(`Failed renderer check: ${script.slice(0, 220)}`); throw error; });
app.on("web-contents-created", (_event, contents) => contents.on("console-message", ({ level, message }) => {
  if ((level === "error" || level === 3) && !message.includes("Canceled: Canceled")) errors.push(message);
}));
async function until(script, label) {
  for (let attempt = 0; attempt < 150; attempt++) { assert.deepEqual(errors, []); if (await evaluate(script)) return; await delay(50); }
  throw new Error(`Timed out: ${label}`);
}
async function press(keyCode, modifiers = []) {
  page.webContents.sendInputEvent({ type: "keyDown", keyCode, modifiers });
  page.webContents.sendInputEvent({ type: "keyUp", keyCode, modifiers });
}
async function reloadProject() {
  await evaluate('document.querySelector(".save-status").click()');
  await until('!!document.querySelector(".save-status.saved")', 'finish saving before project close');
  await evaluate('document.querySelector(".logo-button").click()');
  await until('!!document.querySelector(".directory-project-row")', 'release document session');
  page.reload();
  await until('!!document.querySelector(".directory-project-row, .structured-preview")', 'reload settings');
  if (await evaluate('!!document.querySelector(".directory-project-row")')) await evaluate('document.querySelector(".directory-project-row").click()');
  await until('!!document.querySelector(".structured-table")', 'reopen configured table');
  page.focus();
}
async function run() {
  while (!BrowserWindow.getAllWindows().length) await delay(50);
  page = BrowserWindow.getAllWindows()[0];
  await until('!!window.latexEditor && !!document.querySelector(".project-directory-v044")', "directory");
  const project = await evaluate(`window.latexEditor.projects.create({name:"table-editor-regression",parentPath:${JSON.stringify(projects)}})`);
  const id = JSON.stringify(project.id);
  for (const [key, value] of [['autoSave', 'off'], ['confirmPreviewEdits', false], ['fontSize', 26], ['layout', {mode:'single',singlePane:'preview',leftPane:'preview',rightPane:'pdf'}]]) await evaluate(`window.latexEditor.settings.set(${JSON.stringify(key)}, ${JSON.stringify(value)}, ${id})`);
  const source = "\\documentclass{article}\n\\begin{document}\n\\begin{table}[ht]\n\\begin{tabular}{cc}\nA & B \\\\\n1 & 2 \\\\\n\\end{tabular}\n\\caption{Table caption}\\label{tab:keep}\n\\end{table}\nOutside paragraph.\n\\end{document}";
  const sourceWithWideMath = source.replace('A & B', 'A & $' + 'x'.repeat(320) + '$');
  await evaluate(`window.latexEditor.files.write(${id}, "main.tex", ${JSON.stringify(sourceWithWideMath)})`);
  page.reload();
  await until('!!document.querySelector(".directory-project-row")', "project list");
  await evaluate('document.querySelector(".directory-project-row").click()');
  await until('!!document.querySelector(".structured-table td")', "table preview");
  page.focus();
  assert.equal(await evaluate('document.querySelectorAll(".table-preview-toolbar").length'), 0);
  await evaluate('document.querySelector(".structured-table td").click()');
  await until('!!document.querySelector(".table-floating-tools .table-preview-toolbar")', "selected floating toolbar");
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".table-floating-tools")).position'), 'fixed');
  await until('document.querySelector(".table-floating-tools").getBoundingClientRect().bottom <= document.querySelector(".preview-block[data-environment=table]").getBoundingClientRect().top - 11', "toolbar stays above the entire table block");
  assert.ok(await evaluate('document.querySelector(".table-floating-tools").getBoundingClientRect().width <= document.querySelector(".preview-block[data-environment=table]").getBoundingClientRect().width + 1'));
  await evaluate('Array.from(document.querySelectorAll(".preview-content-region")).find(el => el.textContent.includes("Outside paragraph")).click()');
  await until('!document.querySelector(".table-floating-tools")', "deselection hides toolbar");
  await press('ESC');
  await evaluate('document.querySelector(".table-expand-button").click()');
  await until('!!document.querySelector(".table-editor-dialog .structured-table td")', "expanded editor");
  await until('document.activeElement?.classList.contains("table-editor-close")', 'dialog focus initialized');
  assert.equal(await evaluate('document.querySelectorAll(".table-editor-tools .table-preview-toolbar").length'), 1);
  assert.equal(await evaluate('!!document.querySelector(".table-floating-tools")'), false);
  assert.ok(await evaluate('document.querySelector(".table-editor-dialog").getBoundingClientRect().width > innerWidth * .75'));
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".table-editor-dialog .structured-table")).fontSize'), '15px');
  await evaluate('document.querySelector(".table-editor-dialog .table-column-selectors th:nth-child(2) button").click()');
  await until('document.querySelector(".table-inspector > header strong")?.textContent === "Column 2"', 'column selection reaches inspector');
  await evaluate('document.querySelector(".table-editor-dialog .table-row-selector").click()');
  await until('document.querySelector(".table-inspector > header strong")?.textContent === "Row 1"', 'row selection reaches inspector');
  await until('(() => { const content = document.querySelector(".table-editor-dialog tbody tr:first-child td:nth-child(2) .table-cell-content"); return content.scrollWidth > content.clientWidth; })()', 'wide formula has internal horizontal scrolling');
  await evaluate('document.querySelector(".table-editor-dialog td").click()');
  await until('!!document.querySelector(".table-editor-dialog td textarea")', "edit expanded cell");
  await press('A', ['control']); await page.webContents.insertText('Committed before Tab');
  await press('TAB');
  await until('document.querySelector(".table-inspector > header strong")?.textContent === "Cell 1, 2"', 'Tab synchronizes the current cell with inspector');
  await press('TAB', ['shift']);
  await until('document.querySelector(".table-inspector > header strong")?.textContent === "Cell 1, 1"', 'Shift+Tab restores the first cell');
  assert.equal(await evaluate('document.querySelector(".table-inspector-fields textarea").value'), 'Committed before Tab');
  const longCell = 'Long_' + 'x'.repeat(1800) + '\n' + Array.from({ length: 30 }, (_, index) => `Line ${index}: ` + 'content '.repeat(16)).join('\n');
  await press('A', ['control']); await page.webContents.insertText(longCell);
  await until('document.querySelector(".table-editor-dialog td textarea").scrollWidth > document.querySelector(".table-editor-dialog td textarea").clientWidth && document.querySelector(".table-editor-dialog td textarea").scrollHeight > document.querySelector(".table-editor-dialog td textarea").clientHeight', 'long cell editor has internal scrollbars');
  assert.ok(await evaluate('document.querySelector(".table-editor-dialog td textarea").getBoundingClientRect().width <= document.querySelector(".table-editor-dialog td").getBoundingClientRect().width'));
  await evaluate('document.querySelector(".table-editor-dialog td textarea").scrollTop = 0');
  await delay(200); // Native pointer input needs the resized textarea's presented frame.
  const editorPoint = await evaluate('(() => { const rect = document.querySelector(".table-editor-dialog td textarea").getBoundingClientRect(); return {x:Math.round(rect.left + 30), y:Math.round(rect.top + 30)}; })()');
  page.webContents.sendInputEvent({type:'mouseMove', ...editorPoint});
  page.webContents.sendInputEvent({type:'mouseWheel', ...editorPoint, deltaX:0, deltaY:-100});
  await until('document.querySelector(".table-editor-dialog td textarea").scrollTop > 0', 'wheel scrolls the cell editor');
  await press('ENTER');
  await until('document.querySelector(".table-editor-dialog td .table-cell-content").scrollHeight > document.querySelector(".table-editor-dialog td .table-cell-content").clientHeight', 'long rendered cell scrolls vertically');
  assert.ok(await evaluate('document.querySelector(".table-editor-dialog .structured-table table").getBoundingClientRect().width <= document.querySelector(".table-editor-content").clientWidth'));
  const scrollbarPoint = await evaluate('(() => { const cell = document.querySelector(".table-editor-dialog td .table-cell-content"); cell.scrollTop = 0; const rect = cell.getBoundingClientRect(); return {x:Math.round(rect.right - 5), y:Math.round(rect.top + 20)}; })()');
  page.webContents.sendInputEvent({type:'mouseDown', ...scrollbarPoint, button:'left', clickCount:1});
  page.webContents.sendInputEvent({type:'mouseMove', x:scrollbarPoint.x, y:scrollbarPoint.y + 50});
  page.webContents.sendInputEvent({type:'mouseUp', x:scrollbarPoint.x, y:scrollbarPoint.y + 50, button:'left', clickCount:1});
  await until('!document.querySelector(".table-editor-dialog tbody tr:first-child td:first-child textarea") && document.querySelector(".table-editor-dialog td .table-cell-content").scrollTop > 0', 'scrollbar drag scrolls without opening cell editing');
  await evaluate('document.querySelector(".table-editor-dialog td").click()');
  await until('!!document.querySelector(".table-editor-dialog td textarea")', 'resume editing long cell');
  await press('A', ['control']); await page.webContents.insertText('Edited A'); await press('ENTER');
  await until('document.querySelector(".table-editor-dialog td").textContent.includes("Edited A")', "cell synchronized");
  await evaluate('Array.from(document.querySelectorAll(".table-editor-tools button")).find(button => button.textContent === "Row below").click()');
  await until('document.querySelectorAll(".table-editor-dialog tbody tr").length === 3', "insert row in expanded editor");
  await delay(200); // Let Electron present the updated compositor frame before visual inspection.
  writeFileSync(resolve(root, 'table-editor.png'), (await page.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector(".table-editor-dialog td").click()');
  await until('!!document.querySelector(".table-editor-dialog td textarea")', "final cell draft");
  await press('A', ['control']); await page.webContents.insertText('Saved on close');
  await evaluate('document.querySelector(".table-editor-close").click()');
  await until('!document.querySelector(".table-editor-dialog") && document.querySelector(".structured-table td").textContent.includes("Saved on close")', "close commits cell draft to preview");
  await press('S', ['control']);
  await until(`window.latexEditor.files.read(${id}, "main.tex").then(file => file.content.includes("Saved on close"))`, "save document");
  const saved = (await evaluate(`window.latexEditor.files.read(${id}, "main.tex")`)).content;
  assert.ok(saved.includes('\\caption{Table caption}\\label{tab:keep}'));
  assert.ok(saved.includes('Outside paragraph.'));
  await evaluate('document.querySelector(".table-expand-button").click()');
  await until('!!document.querySelector(".table-editor-dialog")', "reopen expanded editor");
  await press('ESC');
  await until('!document.querySelector(".table-editor-dialog")', "Escape closes expanded editor");
  const catalog = require('../../../../resources/environments/preview-environments.json');
  const definitions = catalog.previewEnvironments.map(entry => ({ ...entry, enabled:true, builtIn:true, labelKey:entry.labelKey ?? `environment.${entry.id}`, style:{...catalog.defaultStyle,...catalog.familyStyles[entry.family],...entry.style}, behavior:{...catalog.defaultBehavior,...entry.behavior} }));
  const configuredTable = definitions.find(entry => entry.id === 'table');
  Object.assign(configuredTable.style, {tableExpandedFontSize:22, tableEditorMaxHeight:90, tableCellMaxHeightEm:4, captionFontSize:19});
  configuredTable.behavior.tableToolbar = 'always';
  await evaluate(`window.latexEditor.settings.set("environments", ${JSON.stringify(definitions)}, ${id})`);
  await reloadProject();
  await until('getComputedStyle(document.querySelector(".structured-table figcaption")).fontSize === "19px"', 'configured caption size');
  await evaluate('document.querySelector(".table-expand-button").click()');
  await until('getComputedStyle(document.querySelector(".table-editor-dialog .structured-table")).fontSize === "22px"', 'configured expanded editor font');
  await evaluate('document.querySelector(".table-editor-dialog td").click()');
  await until('getComputedStyle(document.querySelector(".table-editor-dialog td textarea")).maxHeight === "90px"', 'configured cell editor height');
  await evaluate('document.querySelector(".table-editor-close").click()');
  const { defaultTablePreferences } = await import('@latex-editor/contracts');
  await evaluate(`window.latexEditor.settings.set("tables", ${JSON.stringify({...defaultTablePreferences, editor:{defaultMode:'source'}})}, ${id})`);
  await reloadProject();
  await evaluate('document.querySelector(".structured-table td").click()');
  await until('!!document.querySelector(".preview-local-editor") && !document.querySelector(".structured-table td textarea")', 'existing source editor preference is honored');
  await evaluate('Array.from(document.querySelectorAll(".preview-local-editor-actions button")).find(button => button.textContent === "Cancel").click()');
  await evaluate(`window.latexEditor.settings.set("tables", ${JSON.stringify(defaultTablePreferences)}, ${id})`);
  await reloadProject();
  await evaluate(`window.latexEditor.settings.set("tables", ${JSON.stringify({...defaultTablePreferences, editing:{...defaultTablePreferences.editing, autoAddRowOnTab:true}})}, ${id})`);
  await reloadProject();
  const rowCount = await evaluate('document.querySelectorAll(".structured-table tbody tr").length');
  await evaluate('document.querySelector(".structured-table tbody tr:last-child td:last-child").click()');
  await until('!!document.querySelector(".structured-table td textarea")', 'last cell editing');
  await press('TAB');
  await until(`document.querySelectorAll(".structured-table tbody tr").length === ${rowCount + 1} && !!document.querySelector(".structured-table tbody tr:last-child td:first-child textarea")`, 'existing automatic Tab-row setting is honored');
  Object.assign(configuredTable.behavior, {showCaption:false, captionEditable:false, allowExpandedEditor:false, tableToolbar:'hidden', inlineEditable:false});
  await evaluate(`window.latexEditor.settings.set("environments", ${JSON.stringify(definitions)}, ${id})`);
  await reloadProject();
  await until('!document.querySelector(".structured-table figcaption, .table-expand-button, .table-floating-tools")', 'configured caption/expansion/toolbar hidden');
  await evaluate('document.querySelector(".structured-table td").click()');
  assert.equal(await evaluate('!!document.querySelector(".structured-table td textarea")'), false);
  configuredTable.id = 'renamed-table'; configuredTable.builtIn = false;
  await evaluate(`window.latexEditor.settings.set("environments", ${JSON.stringify(definitions)}, ${id})`);
  await reloadProject();
  await until('!!document.querySelector(\'.preview-block[data-environment="renamed-table"] .structured-table\')', 'renamed table renders by configuration');
  console.log('PASS table preview policy/sizes and renamed environments follow resource configuration');
  assert.deepEqual(errors, []);
  console.log('PASS constrained cells, internal wheel/scrollbar scrolling, floating toolbar, expanded cell/row edits and close');
}
app.whenReady().then(() => {
  require('../../dist/main/index.js');
  run().then(() => { console.log(`Artifacts: ${root}`); app.exit(0); }).catch(error => { console.error(error); console.error(errors); console.error(`Artifacts: ${root}`); app.exit(1); });
});
