const {app,BrowserWindow,dialog}=require('electron');
const {mkdtempSync,mkdirSync,writeFileSync,readFileSync,existsSync}=require('node:fs');
const {join}=require('node:path');
const {tmpdir}=require('node:os');
const assert=require('node:assert/strict');
const root=mkdtempSync(join(tmpdir(),'texweave-maintenance-'));
app.setPath('userData',join(root,'profile')); app.setPath('sessionData',join(root,'profile')); mkdirSync(join(root,'projects'));
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let page;
const evaluate=code=>page.webContents.executeJavaScript(code,true);
async function until(code,label){ for(let i=0;i<200;i++){if(await evaluate(code))return;await delay(50);}throw new Error('Timed out: '+label+'\n'+await evaluate('document.body.innerText.slice(0,2500)')); }
async function run(){
  while(!BrowserWindow.getAllWindows().length)await delay(50);
  page=BrowserWindow.getAllWindows()[0];
  await until('!!window.latexEditor && !!document.querySelector(".directory-topbar")','home');
  const project=await evaluate(`window.latexEditor.projects.create({name:'Keep sources',parentPath:${JSON.stringify(join(root,'projects'))}})`);
  const metadata=join(project.canonicalPath,'.texweave');
  mkdirSync(join(metadata,'build'),{recursive:true});mkdirSync(join(metadata,'history'),{recursive:true});
  writeFileSync(join(metadata,'build','temporary.log'),'Disposable');
  writeFileSync(join(metadata,'history','keep-snapshot'),'History');
  writeFileSync(join(metadata,'settings.json'),'{}');
  const source=readFileSync(join(project.canonicalPath,'main.tex'),'utf8');
  page.reload(); await until('!!document.querySelector(".directory-project-row")','registered project');
  await evaluate(`localStorage.setItem(${JSON.stringify('texweave.workspacePosition:'+JSON.stringify([project.id,project.canonicalPath]))},'{}');localStorage.setItem('retained-draft','Keep');`);
  await evaluate('document.querySelector(".directory-actions > .icon-button:last-child").click()');
  await until('!!document.querySelector("[data-section=applicationBuild]")','separate build category');
  await evaluate('document.querySelector("[data-section=projectBuild]").click()');
  assert.equal(await evaluate('!!document.querySelector("[data-setting=engine]")'),false);
  await evaluate('document.querySelector("[data-section=applicationBuild]").click()');
  assert.ok(await evaluate('!!document.querySelector("[data-setting=engine]") && !!document.querySelector("[data-manager=toolchain]")'));
  await evaluate('document.querySelectorAll(".settings-level-switch button")[1].click()');
  await until('!!document.querySelector(".project-cache-clear-button")','advanced cleanup button');
  writeFileSync(join(root,'settings-maintenance.png'),(await page.webContents.capturePage()).toPNG());
  const original=dialog.showMessageBox; let confirmations=0;
  try{
    dialog.showMessageBox=async()=>{confirmations++;return {response:1};};
    await evaluate('document.querySelector(".project-cache-clear-button").click()');
    await until('!document.querySelector(".project-cache-clear-button").disabled','cancelled cleanup');
    assert.equal(confirmations,1);assert.ok(existsSync(join(metadata,'build','temporary.log')));
    assert.equal((await evaluate('window.latexEditor.projects.list()')).length,1);
    dialog.showMessageBox=async()=>({response:0});
    await evaluate('document.querySelector(".project-cache-clear-button").click()');
    await until('document.querySelector("[role=status]")?.textContent.includes("Removed 1")','cleanup success');
    assert.deepEqual(await evaluate('window.latexEditor.projects.list()'),[]);
    assert.equal(existsSync(join(metadata,'build')),false);
    assert.equal(readFileSync(join(project.canonicalPath,'main.tex'),'utf8'),source);
    assert.equal(readFileSync(join(metadata,'history','keep-snapshot'),'utf8'),'History');
    assert.equal(readFileSync(join(metadata,'settings.json'),'utf8'),'{}');
    assert.equal(await evaluate('localStorage.getItem("retained-draft")'),'Keep');
    assert.equal(await evaluate(`localStorage.getItem(${JSON.stringify('texweave.workspacePosition:'+JSON.stringify([project.id,project.canonicalPath]))})`),null);
    assert.equal((await evaluate('window.latexEditor.settings.get()')).global.lastProject,'');
    await evaluate('document.querySelector(".settings-close").click()');
    await until('!document.querySelector(".directory-project-row")','home list updated');
    page.reload();await until('!!document.querySelector(".directory-topbar")','restarted home');
    assert.deepEqual(await evaluate('window.latexEditor.projects.list()'),[]);
    const reopened=await evaluate(`window.latexEditor.projects.register(${JSON.stringify(project.canonicalPath)})`);
    assert.equal(reopened.canonicalPath,project.canonicalPath);
    page.reload();await until('!!document.querySelector(".directory-project-row")','reopened registration');
    await evaluate('document.querySelector(".directory-project-row").click()');
    await until('!!document.querySelector(\'.tree-row[data-path="main.tex"]\')','project file tree');
    await evaluate('document.querySelector(\'.tree-row[data-path="main.tex"]\').click()');
    await until('Array.from(document.querySelectorAll(".view-switch button")).some(button=>button.textContent==="Code")','text view controls');
    await evaluate('Array.from(document.querySelectorAll(".view-switch button")).find(button=>button.textContent==="Code").click()');
    await until('!!document.querySelector(".editor-surface .monaco-editor")','open editor before cleanup guard');
    page.focus();page.webContents.sendInputEvent({type:'keyDown',keyCode:',',modifiers:['control']});page.webContents.sendInputEvent({type:'keyUp',keyCode:',',modifiers:['control']});
    await until('!!document.querySelector("[data-section=applicationBuild]")','project settings');
    await evaluate('document.querySelector("[data-section=applicationBuild]").click();document.querySelectorAll(".settings-level-switch button")[1].click()');
    await until('!!document.querySelector(".project-cache-clear-button")','cleanup in project settings');
    assert.equal(await evaluate('document.querySelector(".project-cache-clear-button").disabled'),true);
    dialog.showMessageBox=async()=>{throw new Error('Busy projects must not reach confirmation');};
    await assert.rejects(()=>evaluate('window.latexEditor.settings.clearProjectCaches()'),/Close all projects/);
    console.log('PASS settings split, native cancel/confirm, cache/registry cleanup, source/snapshot/settings preservation, view cache removal, restart and re-registration');
  }finally{dialog.showMessageBox=original;}
  console.log('Artifacts: '+root);
}
require('../../dist/main/index.js');
app.whenReady().then(run).then(()=>app.exit(0)).catch(error=>{console.error(error);console.error(root);app.exit(1);});
