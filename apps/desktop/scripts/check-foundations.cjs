const { app, BrowserWindow, dialog } = require("electron");
const { mkdtempSync, mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { resolve } = require("node:path");
const assert = require("node:assert/strict");
const root = mkdtempSync(resolve(tmpdir(), "texweave-foundations-"));
mkdirSync(resolve(root, "projects"));
app.setPath("userData", resolve(root, "user"));
const delay = (ms) => new Promise((done) => setTimeout(done, ms));
let page;
const js = (code) => page.webContents.executeJavaScript(code, true);
async function until(code, label, attempts = 150) {
  for (let i = 0; i < attempts; i++) { if (await js(code)) return; await delay(100); }
  const details = label === 'conflict' ? await js(`JSON.stringify({capture:document.querySelector('[data-shortcut-capture]')?.value,focus:document.activeElement?.outerHTML?.slice(0,240),alerts:Array.from(document.querySelectorAll('.shortcut-inline-recorder [role]')).map(node=>({role:node.getAttribute('role'),text:node.textContent})),recorder:document.querySelector('.shortcut-inline-recorder')?.innerText})`) : '';
  throw new Error(`Timeout: ${label}\n${details}\n${await js('document.body.innerText.slice(0,1500)')}`);
}
const click = async (selector) => {
  if (!await js(`!!document.querySelector(${JSON.stringify(selector)})`)) throw new Error(`Missing click target: ${selector}\n${await js('document.body.innerText.slice(0,1000)')}`);
  await js(`document.querySelector(${JSON.stringify(selector)}).click()`);
};
const select = (selector, value) => js(`(() => { const el=document.querySelector(${JSON.stringify(selector)}); el.value=${JSON.stringify(value)}; el.dispatchEvent(new Event('change',{bubbles:true})); })()`);
function key(keyCode, modifiers) { page.webContents.sendInputEvent({type:"keyDown",keyCode,modifiers}); page.webContents.sendInputEvent({type:"keyUp",keyCode,modifiers}); }
async function checkStylePicker() {
  const imported = [];
  for (let index = 0; index < 40; index++) {
    const stem = 'journal-' + String(index).padStart(2, '0'), path = resolve(root, stem + '.sty');
    writeFileSync(path, '\\ProvidesPackage{' + stem + '}\n');
    imported.push(await js(`window.latexEditor.styleResources.importFiles([${JSON.stringify(path)}],${JSON.stringify('Template ' + index + ' — A long journal style name for checking truncation and large collections')})`));
  }
  page.reload(); await until('!!document.querySelector(".directory-new-main")', 'styles refreshed');
  await click('.directory-new-main'); await click('.style-picker-entry');
  await until('document.querySelectorAll(".style-selector-list input").length === 42', 'forty user styles and two built-in styles');
  await click('.style-selector-item[data-resource-id="default"] input');
  assert.equal(await js('document.querySelector(".style-selector-empty").getAttribute("aria-pressed")'), 'true');
  await click(`.style-selector-item[data-resource-id="${imported[0].id}"] input`);
  assert.equal(await js('document.querySelector(".style-selector-item[data-resource-id=default] input").checked'), false);
  await click('.style-selector-item[data-resource-id="light"] input');
  await click('.style-selector-item[data-resource-id="default"] input');
  assert.equal(await js('document.querySelector(".style-selector-item[data-resource-id=light] input").checked'), false);
  await js(`(() => { const input=document.querySelector('.style-selector-search'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'journal-37.sty'); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await until('document.querySelectorAll(".style-selector-list input").length === 1', 'search by .sty filename');
  await click('.style-selector-list input');
  await js(`(() => { const input=document.querySelector('.style-selector-search'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,''); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await click('.style-selector-tools > div button:last-child');
  await until('document.querySelectorAll(".style-selector-list input").length === 3', 'selected-only view');
  await click('.style-selector-tools > div button:first-child');
  const bounds = await js(`(() => { const dialog=document.querySelector('.style-selector'), list=document.querySelector('.style-selector-list'), rect=dialog.getBoundingClientRect(); return {top:rect.top,bottom:rect.bottom,height:innerHeight,scrolls:list.scrollHeight>list.clientHeight,overflow:dialog.scrollWidth-dialog.clientWidth}; })()`);
  assert.ok(bounds.top >= 0 && bounds.bottom <= bounds.height && bounds.scrolls && bounds.overflow <= 1, JSON.stringify(bounds));
  writeFileSync(resolve(root, 'style-picker-many.png'), (await page.webContents.capturePage()).toPNG());
  await click('.style-selector-item[data-resource-id="default"] input');
  await click('.style-selector footer button');
  const summary = await js(`(() => { const text=document.querySelector('.style-picker-summary strong'), card=document.querySelector('.project-creation-card').getBoundingClientRect(); return {font:parseFloat(getComputedStyle(text).fontSize),ellipsis:getComputedStyle(text).textOverflow,truncated:text.scrollWidth>text.clientWidth,badge:document.querySelector('.style-picker-count')?.textContent,fits:card.left>=0 && card.right<=innerWidth}; })()`);
  assert.ok(summary.font <= 15 && summary.truncated && summary.fits, JSON.stringify(summary)); assert.equal(summary.ellipsis, 'ellipsis'); assert.equal(summary.badge, '+1');
  await click('.style-picker-entry'); await click('.style-selector-clear');
  assert.equal(await js('document.querySelectorAll(".style-selector-list input:checked").length'), 0);
  await click('.style-selector footer button');
  assert.equal(await js('document.querySelector(".style-picker-summary strong").textContent'), 'Empty');
  await js(`(() => { const inputs=document.querySelectorAll('.project-creation-card .field-label input'); for (const [index,value] of ${JSON.stringify(['foundation-empty-ui', resolve(root, 'projects')])}.entries()) { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(inputs[index],value); inputs[index].dispatchEvent(new Event('input',{bubbles:true})); } })()`);
  await click('.project-creation-card .modal-actions .primary-button');
  await until('!document.querySelector(".project-creation-card")', 'create project with no selected styles');
  const folder = resolve(root, 'projects/foundation-empty-ui');
  assert.equal(readdirSync(folder).some(name => name.endsWith('.sty')), false);
  assert.doesNotMatch(readFileSync(resolve(folder, 'main.tex'), 'utf8'), /\\usepackage/);
  console.log('PASS optional/Empty styles, custom-only selection, built-in exclusivity, filename search, selected-only view, bounded 40-style list and compact summary');
}
async function run() {
  for (let i = 0; i < 150 && !BrowserWindow.getAllWindows().length; i++) await delay(100);
  page = BrowserWindow.getAllWindows()[0];
  assert.ok(page);
  await until('!!document.querySelector(".directory-topbar")', "directory");
  await checkStylePicker();
  await click('.directory-actions > .icon-button:last-child');
  await click('[data-section="general"]');
  await select('[data-setting="locale"] select', 'ja');
  await until('document.querySelector(".preferences-dialog h1").textContent === "設定"', 'live Japanese');
  await click('[data-section="appearance"]');
  await until('Array.from(document.querySelectorAll("[data-setting=theme] option")).some((option) => option.value === "dark")', 'theme choices');
  await select('[data-setting="theme"]', 'dark');
  await until('document.documentElement.dataset.theme === "dark"', 'dark theme');
  page.reload();
  await until('!!document.querySelector(".directory-topbar") && document.documentElement.lang === "ja" && document.documentElement.dataset.theme === "dark"', 'persisted locale/theme');
  console.log('PASS live Japanese, dark theme and persistence across renderer reload');
  await click('.directory-actions > .icon-button:last-child');
  await click('[data-section="projectBuild"]');
  await js('document.querySelectorAll(".settings-level-switch button")[1].click()');
  await until('!!document.querySelector(".settings-manager-entry-open[data-manager=\\"styleResources\\"]")', 'advanced project managers');
  await click('.settings-manager-entry-open[data-manager="styleResources"]');
  await until('document.querySelector(".style-resources-page")', 'style resource settings');
  const resources = await js('window.latexEditor.styleResources.list()');
  assert.ok(resources.some((item) => item.id === 'empty' && item.source === 'built-in'));
  assert.ok(resources.some((item) => item.id === 'default' && item.files.some((file) => file.targetPath === 'texweave.sty')));
  await click('.settings-manager-return');
  const project = await js(`window.latexEditor.projects.create({name:'foundation-a',parentPath:${JSON.stringify(resolve(root,"projects"))},styleResourceIds:['default']})`);
  const emptyProject = await js(`window.latexEditor.projects.create({name:'foundation-empty',parentPath:${JSON.stringify(resolve(root,"projects"))},styleResourceIds:['empty']})`);
  assert.ok(existsSync(resolve(project.canonicalPath, 'texweave.sty')));
  assert.ok(existsSync(resolve(project.canonicalPath, 'reference.bib')));
  assert.match(readFileSync(resolve(project.canonicalPath, 'main.tex'), 'utf8'), /\\usepackage\{texweave\}/);
  assert.equal(existsSync(resolve(emptyProject.canonicalPath, 'texweave.sty')), false);
  const importedPath = resolve(root, 'custom-style.sty');
  writeFileSync(importedPath, '\\ProvidesPackage{customstyle}\n', 'utf8');
  const custom = await js(`window.latexEditor.styleResources.importFiles([${JSON.stringify(importedPath)}], 'Custom Style')`);
  const customProject = await js(`window.latexEditor.projects.create({name:'foundation-custom',parentPath:${JSON.stringify(resolve(root,"projects"))},styleResourceIds:['empty',${JSON.stringify(custom.id)}]})`);
  assert.ok(existsSync(resolve(customProject.canonicalPath, 'custom-style.sty')));
  assert.match(readFileSync(resolve(customProject.canonicalPath, 'main.tex'), 'utf8'), /\\usepackage\{custom-style\}/);
  console.log('PASS built-in/custom style resources, project-local snapshots and bootstrap files');
  const other = await js(`window.latexEditor.projects.create({name:'foundation-b',parentPath:${JSON.stringify(resolve(root,"projects"))}})`);
  await js(`window.latexEditor.settings.set('fontSize',22,${JSON.stringify(project.id)})`);
  const isolated = await js(`window.latexEditor.settings.get(${JSON.stringify(other.id)})`);
  assert.equal(isolated.project.fontSize, undefined);
  const toolchain = (await js('window.latexEditor.settings.get()')).toolchain;
  assert.equal(toolchain.available, true);
  assert.ok(toolchain.latexmk);
  const globalFile = JSON.parse(readFileSync(resolve(root,"user/settings.json"),'utf8'));
  assert.equal(globalFile.preferences.locale, 'ja');
  assert.ok(globalFile.toolchain.latexmk);
  const projectFile = JSON.parse(readFileSync(resolve(project.canonicalPath,'.texweave/settings.json'),'utf8'));
  assert.equal(projectFile.toolchain, undefined);
  console.log('PASS global toolchain persistence and project isolation');
  // Exercise the same manual selection handler without requiring an OS dialog.
  const originalDialog = dialog.showOpenDialog;
  dialog.showOpenDialog = async () => ({ canceled:false, filePaths:[toolchain.binDirectory] });
  const manual = await js('window.latexEditor.settings.detectToolchain("directory")');
  dialog.showOpenDialog = originalDialog;
  assert.equal(manual.available,true);
  await js("window.latexEditor.settings.set('locale','en')");
  page.reload();
  await until('document.querySelectorAll(".directory-project-row").length >= 4','projects');
  await click('.directory-project-row');
  await until('!!document.querySelector(".editor-surface .monaco-editor")','editor');
  await until('!Array.from(document.querySelectorAll(".tree-row")).some((row) => row.dataset.path === ".texweave")','hidden TeXWeave metadata');
  key(',', ['control']);
  await until('!!document.querySelector(".preferences-dialog")','general settings open');
  await click('[data-section="general"]');
  assert.ok(await js('!!document.querySelector("[data-setting=hideBuildArtifacts]")'));
  await click('.settings-close');
  const workbenchTheme = await js(`(() => { const root=getComputedStyle(document.documentElement); const pick=(selector,property='backgroundColor')=>getComputedStyle(document.querySelector(selector))[property]; return { theme:document.documentElement.dataset.theme, activity:pick('.activity-bar'), sidebar:pick('.sidebar'), toolbar:pick('.latex-toolbar'), token:root.getPropertyValue('--color-bg-toolbar').trim(), active:pick('.tree-row.active') }; })()`);
  assert.equal(workbenchTheme.theme, 'dark');
  console.log('PASS dark theme persists on the directory shell');
  key(',', ['control']);
  await until('!!document.querySelector(".preferences-dialog")','shortcut settings open');
  await click('[data-section="editor"]');
  await click('.settings-manager-entry-open[aria-label="Shortcut manager"]');
  await js(`Array.from(document.querySelectorAll('.shortcut-map-function')).find(item => item.querySelector('.shortcut-map-function-name strong')?.textContent.trim() === 'Compile').querySelector('.shortcut-map-function-select').click()`);
  await until('!!document.querySelector("[data-shortcut-capture]")', 'shortcut capture input');
  await delay(120);
  await js('document.querySelector("[data-shortcut-capture]").focus()');
  key('A',['control','shift']);
  await delay(100);
  await until('!!document.querySelector(".shortcut-inline-recorder [role=alert]")','conflict');
  await js(`Array.from(document.querySelectorAll('.shortcut-inline-recorder-actions button')).find(button => button.textContent.trim() === 'Cancel').click()`);
  await until('!document.querySelector("[data-shortcut-capture]")', 'cancel conflict capture');
  await js(`Array.from(document.querySelectorAll('.shortcut-map-function')).find(item => item.querySelector('.shortcut-map-function-name strong')?.textContent.trim() === 'Compile').querySelector('.shortcut-map-function-select').click()`);
  await until('!!document.querySelector("[data-shortcut-capture]")', 'shortcut recapture input');
  await delay(120);
  await js('document.querySelector("[data-shortcut-capture]").focus()');
  key('L',['control','shift']);
  await until('document.querySelector("[data-shortcut-capture]")?.value.includes("Ctrl+Shift+L")', 'replacement shortcut preview');
  await js(`Array.from(document.querySelectorAll('.shortcut-inline-recorder-actions button')).find(button => button.textContent.trim() === 'Use this shortcut').click()`);
  await until('!document.querySelector("[data-shortcut-capture]")','rebind');
  assert.equal((await js('window.latexEditor.settings.get()')).global.keybindings['latex.compile'],'Mod+Shift+L');
  await click('.settings-manager-return');
  await click('.settings-close');
  key('L',['control','shift']);
  // This is the first full TeX compilation in a fresh app profile and may need
  // longer while MiKTeX loads the project's starter packages on a cold cache.
  await until('document.querySelector(".status-bar").textContent.includes("Last compile succeeded")','rebound compilation', 600);
  console.log('PASS shortcut conflict, live rebinding and actual compilation');
  console.log('Artifacts:', root);
}
require('../dist/main/index.js');
app.whenReady().then(run).then(()=>app.exit(0)).catch((error)=>{console.error(error); console.error(root); app.exit(1);});
